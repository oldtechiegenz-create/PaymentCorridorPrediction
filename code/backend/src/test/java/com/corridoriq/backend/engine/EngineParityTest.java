package com.corridoriq.backend.engine;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

import org.junit.jupiter.api.Test;
import org.sqlite.SQLiteConfig;
import org.sqlite.SQLiteDataSource;

import com.corridoriq.backend.engine.RouteEstimator.RouteEstimate;

/**
 * The Java engine against the Python engine. The history database was generated by code/scripts, so each
 * route_candidate row holds what the Python simulator estimated at release. This test re-estimates a sample of
 * those payments in Java and requires the same numbers. It is skipped when the database is not present.
 */
class EngineParityTest {

    private static final Path DB = Path.of("../../Data/corridoriq_history/corridoriq_history.db").toAbsolutePath().normalize();
    /** The database stores 2-decimal values; allow one unit of the second decimal for rounding at a boundary. */
    private static final double TOL = 0.011;

    @Test
    void estimatesMatchWhatPythonStored() throws Exception {
        assumeTrue(Files.isRegularFile(DB), "history database not found at " + DB);
        SQLiteConfig cfg = new SQLiteConfig();
        cfg.setReadOnly(true);
        SQLiteDataSource ds = new SQLiteDataSource(cfg);
        ds.setUrl("jdbc:sqlite:" + DB);

        List<String> mismatches = new ArrayList<>();
        int payments = 0;
        int candidates = 0;
        try (Connection c = ds.getConnection()) {
            BankCalendar cal = BankCalendar.fromDatabase(c);
            try (Statement st = c.createStatement();
                 ResultSet p = st.executeQuery("SELECT payment_id, corridor_id, bene_bank_id, client_type, amount_usd, "
                         + "released_at_utc FROM payment WHERE payment_id % 20 = 0 ORDER BY payment_id");
                 PreparedStatement byPayment = c.prepareStatement("SELECT * FROM route_candidate WHERE payment_id = ?")) {
                while (p.next()) {
                    long pid = p.getLong("payment_id");
                    List<RouteEstimate> java = RouteEstimator.estimate(p.getString("corridor_id"),
                            p.getString("bene_bank_id"), p.getString("client_type"), p.getDouble("amount_usd"),
                            Instant.parse(p.getString("released_at_utc")), cal).stream().map(RouteEstimate::rounded).toList();
                    Map<String, RouteEstimate> byTemplate = new HashMap<>();
                    java.forEach(e -> byTemplate.put(e.templateId(), e));

                    byPayment.setLong(1, pid);
                    int rows = 0;
                    try (ResultSet r = byPayment.executeQuery()) {
                        while (r.next()) {
                            rows++;
                            candidates++;
                            String tid = r.getString("template_id");
                            RouteEstimate e = byTemplate.get(tid);
                            if (e == null) {
                                mismatches.add(pid + " " + tid + ": route missing in Java");
                                continue;
                            }
                            compare(mismatches, pid, tid, "eligible", r.getInt("eligible") == 1 ? 1 : 0, e.eligible() ? 1 : 0);
                            compare(mismatches, pid, tid, "exclusion_reason", r.getString("exclusion_reason"),
                                    e.ineligibleReasons().isEmpty() ? null : String.join("; ", e.ineligibleReasons()));
                            compare(mismatches, pid, tid, "hop_count", r.getInt("hop_count"), e.hopCount());
                            compare(mismatches, pid, tid, "intermediaries", r.getInt("intermediaries"), e.intermediaries());
                            compare(mismatches, pid, tid, "max_risk", r.getInt("max_risk"), e.maxRisk());
                            compare(mismatches, pid, tid, "calendar_conflict", r.getInt("calendar_conflict"), e.calendarConflict() ? 1 : 0);
                            compare(mismatches, pid, tid, "est_nonbusiness_days", r.getInt("est_nonbusiness_days"), e.estNonbusinessDays());
                            near(mismatches, pid, tid, "fee_total_usd", r.getDouble("fee_total_usd"), e.feeTotalUsd());
                            near(mismatches, pid, tid, "fx_bps", r.getDouble("fx_bps"), e.fxBps());
                            near(mismatches, pid, tid, "est_cost_usd", r.getDouble("est_cost_usd"), e.estCostUsd());
                            near(mismatches, pid, tid, "est_hours", r.getDouble("est_hours"), e.estHours());
                            near(mismatches, pid, tid, "naive_hours", r.getDouble("naive_hours"), e.naiveHours());
                            near(mismatches, pid, tid, "cutoff_slack_hours", r.getDouble("cutoff_slack_hours"), e.cutoffSlackHours());
                            near(mismatches, pid, tid, "stp_rate_nominal", r.getDouble("stp_rate_nominal"), e.stpRateNominal());
                        }
                    }
                    if (rows != java.size()) {
                        mismatches.add(pid + ": Python stored " + rows + " routes, Java estimated " + java.size());
                    }
                    payments++;
                }
            }
        }
        assertThat(payments).as("payments compared").isGreaterThan(1500);
        assertThat(candidates).as("candidate routes compared").isGreaterThan(7000);
        assertThat(mismatches).as("mismatches between Java and Python estimates (first shown)")
                .isEmpty();
    }

    private static void compare(List<String> out, long pid, String tid, String field, Object fromPython, Object fromJava) {
        if (!Objects.equals(fromJava, fromPython)) {
            out.add(pid + " " + tid + " " + field + ": python=" + fromPython + " java=" + fromJava);
        }
    }

    private static void near(List<String> out, long pid, String tid, String field, double fromPython, double fromJava) {
        if (Math.abs(fromPython - fromJava) > TOL) {
            out.add(pid + " " + tid + " " + field + ": python=" + fromPython + " java=" + fromJava);
        }
    }
}
